import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { z } from 'zod';

import type { WgEasyApi } from '../api.js';
import { errorResult, jsonResult, run, textResult } from '../result.js';

const clientId = z.coerce
  .number()
  .int()
  .positive()
  .describe('Numeric ID of the client (see list_clients)');

/**
 * Fields of the wg-easy `ClientUpdateSchema`. The update endpoint expects the
 * complete object, so `update_client` merges partial input into the current
 * client state before posting.
 */
const UPDATABLE_FIELDS = [
  'name',
  'enabled',
  'expiresAt',
  'ipv4Address',
  'ipv6Address',
  'preUp',
  'postUp',
  'preDown',
  'postDown',
  'allowedIps',
  'serverAllowedIps',
  'firewallIps',
  'mtu',
  'jC',
  'jMin',
  'jMax',
  'i1',
  'i2',
  'i3',
  'i4',
  'i5',
  'persistentKeepalive',
  'serverEndpoint',
  'dns',
] as const;

export function registerClientTools(server: McpServer, api: WgEasyApi): void {
  server.registerTool(
    'list_clients',
    {
      title: 'List WireGuard clients',
      description:
        'List all WireGuard clients of the wg-easy instance, including their status (enabled/expired), addresses and traffic statistics.',
      inputSchema: {
        filter: z
          .string()
          .optional()
          .describe('Optional name filter (substring match)'),
        sort: z
          .enum(['asc', 'desc'])
          .optional()
          .describe('Sort by name, ascending or descending'),
      },
      annotations: { readOnlyHint: true },
    },
    ({ filter, sort }) =>
      run(async () => {
        const query = new URLSearchParams();
        if (filter) query.set('filter', filter);
        if (sort) query.set('sort', sort);
        const suffix = query.size > 0 ? `?${query.toString()}` : '';
        return jsonResult(await api.get(`/api/client${suffix}`));
      })
  );

  server.registerTool(
    'get_client',
    {
      title: 'Get WireGuard client',
      description: 'Get the full details of a single WireGuard client.',
      inputSchema: { clientId },
      annotations: { readOnlyHint: true },
    },
    ({ clientId }) =>
      run(async () => jsonResult(await api.get(`/api/client/${clientId}`)))
  );

  server.registerTool(
    'create_client',
    {
      title: 'Create WireGuard client',
      description:
        'Create a new WireGuard client. Keys and IP addresses are generated by wg-easy. Returns the new client ID.',
      inputSchema: {
        name: z.string().min(1).describe('Display name of the new client'),
        expiresAt: z
          .string()
          .optional()
          .describe(
            'Optional expiry date as ISO string (e.g. 2026-12-31). Omit for no expiry.'
          ),
      },
      annotations: {},
    },
    ({ name, expiresAt }) =>
      run(async () =>
        jsonResult(
          await api.post('/api/client', { name, expiresAt: expiresAt ?? null })
        )
      )
  );

  server.registerTool(
    'update_client',
    {
      title: 'Update WireGuard client',
      description:
        'Update a WireGuard client. Only the provided fields are changed; all other settings are preserved.',
      inputSchema: {
        clientId,
        name: z.string().min(1).optional().describe('New display name'),
        enabled: z
          .boolean()
          .optional()
          .describe('Enable or disable the client'),
        expiresAt: z
          .string()
          .nullable()
          .optional()
          .describe('Expiry date as ISO string, or null to remove the expiry'),
        ipv4Address: z
          .string()
          .optional()
          .describe('IPv4 address of the client'),
        ipv6Address: z
          .string()
          .optional()
          .describe('IPv6 address of the client'),
        allowedIps: z
          .array(z.string())
          .nullable()
          .optional()
          .describe(
            'CIDRs routed through the tunnel on the client side, or null to use the server default'
          ),
        serverAllowedIps: z
          .array(z.string())
          .optional()
          .describe('Additional CIDRs the server routes to this client'),
        dns: z
          .array(z.string())
          .nullable()
          .optional()
          .describe(
            'DNS servers for the client, or null to use the server default'
          ),
        mtu: z.number().int().optional().describe('MTU for the client'),
        persistentKeepalive: z
          .number()
          .int()
          .optional()
          .describe('Persistent keepalive interval in seconds (0 = off)'),
      },
      annotations: {},
    },
    ({ clientId, ...changes }) =>
      run(async () => {
        // The API expects the complete update object, so merge the partial
        // input into the current client state.
        const current = (await api.get(`/api/client/${clientId}`)) as Record<
          string,
          unknown
        >;
        const body: Record<string, unknown> = {};
        for (const field of UPDATABLE_FIELDS) {
          body[field] = current[field] ?? null;
        }
        for (const [key, value] of Object.entries(changes)) {
          if (value !== undefined) body[key] = value;
        }
        return jsonResult(await api.post(`/api/client/${clientId}`, body));
      })
  );

  server.registerTool(
    'enable_client',
    {
      title: 'Enable WireGuard client',
      description: 'Enable a WireGuard client so it can connect again.',
      inputSchema: { clientId },
      annotations: { idempotentHint: true },
    },
    ({ clientId }) =>
      run(async () =>
        jsonResult(await api.post(`/api/client/${clientId}/enable`))
      )
  );

  server.registerTool(
    'disable_client',
    {
      title: 'Disable WireGuard client',
      description:
        'Disable a WireGuard client. The client keeps its configuration but can no longer connect.',
      inputSchema: { clientId },
      annotations: { idempotentHint: true },
    },
    ({ clientId }) =>
      run(async () =>
        jsonResult(await api.post(`/api/client/${clientId}/disable`))
      )
  );

  server.registerTool(
    'delete_client',
    {
      title: 'Delete WireGuard client',
      description:
        'Permanently delete a WireGuard client. This is irreversible: the client loses VPN access and its keys cannot be restored. Requires confirm=true.',
      inputSchema: {
        clientId,
        confirm: z
          .boolean()
          .default(false)
          .describe(
            'Must be true to actually delete the client. Ask the user for confirmation first.'
          ),
      },
      annotations: { destructiveHint: true },
    },
    ({ clientId, confirm }) =>
      run(async () => {
        const current = (await api.get(`/api/client/${clientId}`)) as {
          name?: string;
        };
        if (!confirm) {
          return errorResult(
            `Refusing to delete client ${clientId} ("${current.name ?? 'unknown'}") without confirmation. ` +
              'Deleting is irreversible. Call delete_client again with confirm=true after the user confirmed.'
          );
        }
        await api.delete(`/api/client/${clientId}`);
        return textResult(
          `Client ${clientId} ("${current.name ?? 'unknown'}") deleted.`
        );
      })
  );

  server.registerTool(
    'get_client_config',
    {
      title: 'Get WireGuard client configuration',
      description:
        'Get the WireGuard configuration file (wg .conf format, including the private key) for a client.',
      inputSchema: { clientId },
      annotations: { readOnlyHint: true },
    },
    ({ clientId }) =>
      run(async () =>
        textResult(
          String(await api.get(`/api/client/${clientId}/configuration`))
        )
      )
  );

  server.registerTool(
    'get_client_qrcode',
    {
      title: 'Get WireGuard client QR code',
      description:
        'Get the client configuration as a QR code (SVG markup) for scanning with the WireGuard mobile app.',
      inputSchema: { clientId },
      annotations: { readOnlyHint: true },
    },
    ({ clientId }) =>
      run(async () =>
        textResult(String(await api.get(`/api/client/${clientId}/qrcode.svg`)))
      )
  );

  server.registerTool(
    'generate_one_time_link',
    {
      title: 'Generate one-time config link',
      description:
        'Generate a one-time download link for a client configuration that can be shared with the end user. Requires WG_ENABLE_ONE_TIME_LINKS to be enabled on the wg-easy instance.',
      inputSchema: { clientId },
      annotations: {},
    },
    ({ clientId }) =>
      run(async () => {
        await api.post(`/api/client/${clientId}/generateOneTimeLink`);
        const client = (await api.get(`/api/client/${clientId}`)) as {
          oneTimeLink?: { oneTimeLink?: string } | string | null;
        };
        const link =
          typeof client.oneTimeLink === 'string'
            ? client.oneTimeLink
            : client.oneTimeLink?.oneTimeLink;
        if (!link) {
          return jsonResult({
            success: true,
            note: 'One-time link generated, but the link value was not returned by the API. Check the wg-easy UI.',
          });
        }
        return jsonResult({
          success: true,
          oneTimeLink: link,
          path: `/cnf/${link}`,
        });
      })
  );
}
